package com.rumi.maintenance.infrastructure.web.dto;

import com.rumi.maintenance.domain.model.FindingSeverity;
import com.rumi.maintenance.domain.model.InspectionStatus;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.Instant;
import java.time.LocalDate;
import java.util.List;
import java.util.UUID;

@Schema(name = "InspectionResponse", description = "An inspection in the calendar of a building")
public record InspectionResponseDto(
        @Schema(description = "Identifier generated by the service", example = "3e1f5a7c-2b4d-4c6e-8f0a-1b3d5f7a9c21")
        UUID id,
        @Schema(description = "Building to inspect", example = "7a9b3c1d-2e4f-4b6a-8c0d-1e2f3a4b5c6d")
        UUID buildingId,
        @Schema(description = "Engineer responsible for the visit", example = "Ing. Carla Mendoza")
        String engineerName,
        @Schema(description = "Date of the visit", example = "2026-11-27")
        LocalDate scheduledDate,
        @Schema(description = "PENDING, IN_PROGRESS, COMPLETED or CANCELLED", example = "PENDING")
        InspectionStatus status,
        @Schema(description = "Most severe finding; null while there are no findings", example = "HIGH",
                nullable = true)
        FindingSeverity highestSeverity,
        @Schema(description = "When the inspection was scheduled (UTC)", example = "2026-11-20T16:00:00Z")
        Instant createdAt,
        @Schema(description = "When the visit started (UTC)", nullable = true)
        Instant startedAt,
        @Schema(description = "When the visit was completed (UTC)", nullable = true)
        Instant completedAt,
        @Schema(description = "Findings recorded during the visit, oldest first")
        List<InspectionFindingResponseDto> findings
) {
}
