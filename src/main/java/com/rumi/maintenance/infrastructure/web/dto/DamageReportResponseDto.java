package com.rumi.maintenance.infrastructure.web.dto;

import com.rumi.maintenance.domain.model.DamageReportStatus;
import com.rumi.maintenance.domain.model.FindingSeverity;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.Instant;
import java.util.UUID;

@Schema(name = "DamageReportResponse", description = "A damage report of a building")
public record DamageReportResponseDto(
        @Schema(description = "Identifier generated by the service", example = "8c2e4a6f-1b3d-4f5a-9c7e-2d4f6a8c0e13")
        UUID id,
        @Schema(description = "Building where the damage is", example = "7a9b3c1d-2e4f-4b6a-8c0d-1e2f3a4b5c6d")
        UUID buildingId,
        @Schema(description = "Resident who reported it; null when the request did not come through the gateway",
                example = "d4e5f6a7-b8c9-4d0e-9f1a-2b3c4d5e6f70", nullable = true)
        UUID residentUserId,
        @Schema(description = "What the resident sees", example = "Crack in the wall next to the elevator")
        String description,
        @Schema(description = "Where the damage is", example = "FLOOR-2-EAST")
        String zone,
        @Schema(description = "Address of the photo", example = "https://storage.example.com/rumi/damage/floor2-wall.jpg")
        String photoUrl,
        @Schema(description = "When the photo was taken (UTC)", nullable = true)
        Instant photoTakenAt,
        @Schema(description = "LOW, MEDIUM or HIGH, assigned by the administrator; null until reviewed",
                example = "HIGH", nullable = true)
        FindingSeverity severity,
        @Schema(description = "REPORTED, UNDER_REVIEW or RESOLVED", example = "REPORTED")
        DamageReportStatus status,
        @Schema(description = "Inspection scheduled to evaluate the damage", nullable = true)
        UUID generatedInspectionId,
        @Schema(description = "When the damage was reported (UTC)", example = "2026-11-20T13:50:00Z")
        Instant reportedAt,
        @Schema(description = "When the administrator reviewed it (UTC)", nullable = true)
        Instant reviewedAt,
        @Schema(description = "When it was resolved (UTC)", nullable = true)
        Instant resolvedAt
) {
}
